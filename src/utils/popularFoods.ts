// 検索語に合う「よく食べるもの」を、成分表の値（混ぜるものは計算した値）にして返す
//   1つの食品なら code は成分表の食品番号のまま、混ぜたものは '01088+01170' のようにつなぐ
export function searchPopularFoods(mextFoods: MextFood[], query: string): MextFood[] {
  const byCode = new Map(mextFoods.map((food) => [food.code, food]));
  // 検索は「名前 + キーワード」を1つの文字列にして、成分表と同じ仕組みで行う
  const targets = POPULAR_FOODS.map((item) => ({
    item,
    name: [item.label, ...item.keywords].join(' '),
  }));
  // 並び順は一覧に書いた順（ごはんなら白米 → 玄米 → 麦ごはん…の順に出す）
  const hits = new Set(searchFoods(targets, query, POPULAR_FOODS.length).map((t) => t.item));

  const results: MextFood[] = [];
  for (const item of POPULAR_FOODS.filter((i) => hits.has(i))) {
    const parts = item.parts.map((p) => ({ food: byCode.get(p.code), ratio: p.ratio }));
    if (parts.some((p) => !p.food)) continue; // 成分表が変わって見つからないときは出さない
    const sum = (key: 'kcal' | 'protein' | 'fat' | 'carbs') =>
      round1(parts.reduce((total, p) => total + p.food![key] * p.ratio, 0));
    results.push({
      code: item.parts.map((p) => p.code).join('+'),
      // 1つの食品なら成分表の名前（どの食品の値か分かるように）、混ぜたものは表示名
      name: item.parts.length === 1 ? parts[0].food!.name : item.label,
      label: item.label,
      ...(item.basis ? { basis: item.basis } : {}),
      kcal: sum('kcal'),
      protein: sum('protein'),
      fat: sum('fat'),
      carbs: sum('carbs'),
    });
  }
  return results;
}
