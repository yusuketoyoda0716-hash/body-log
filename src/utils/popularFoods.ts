// よく食べるものを、成分表の名前ではなく分かりやすい名前で上に出すための一覧
//   keywords：この言葉で検索したときに出す
//   parts：成分表の食品番号と割合。2つ以上なら、その割合で混ぜた値を計算する（例：麦ごはん）
type PopularFood = {
  label: string;
  keywords: string[];
  parts: { code: string; ratio: number }[];
  basis?: string; // 混ぜて計算したときの説明
};

