const one = (code: string) => [{ code, ratio: 1 }];

// 1つの食品をそのまま使うものは、この形で短く書く
const food = (label: string, code: string, keywords: string[]): PopularFood => ({
  label,
  keywords,
  parts: one(code),
});

// 牛肉は「国産牛（乳用肥育牛）・輸入牛・和牛」で値がかなり違うので、それぞれ用意する
const beef = (
  cut: string,
  codes: { 国産?: string; 輸入?: string; 和牛?: string },
  keywords: string[],
) =>
  (['国産', '輸入', '和牛'] as const).flatMap((kind) => {
    const code = codes[kind];
    if (!code) return [];
    const kindWords =
      kind === '国産' ? ['国産牛', '国産'] : kind === '輸入' ? ['輸入牛', '輸入'] : ['和牛'];
    return [
      food(`牛${cut}（${kind === '和牛' ? '和牛' : kind}）`, code, [
        ...BEEF,
        ...keywords,
        ...kindWords,
      ]),
    ];
  });

